  const safeTareas = Array.isArray(tareas) ? tareas : [];
  const folioPry = p?.id || (p?.idNumerico ? `PRY-${String(p.idNumerico).padStart(3, '0')}` : '');
  const idNumStr = p?.idNumerico ? String(p.idNumerico) : '';

